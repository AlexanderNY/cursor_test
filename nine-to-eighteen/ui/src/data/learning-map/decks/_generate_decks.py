"""Generate TopicDeck TypeScript modules. Run from repo: python _generate_decks.py"""
from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent


def slugify(text: str) -> str:
    out = []
    for ch in text.lower():
        if ch.isalnum():
            out.append(ch)
        elif ch in " -_/":
            out.append("-")
    s = "".join(out)
    while "--" in s:
        s = s.replace("--", "-")
    return s.strip("-")[:48] or "card"


def emit_deck(
    filename: str,
    export_name: str,
    branch_title: str,
    cards: list[tuple[str, str, str, str | None]],
    source_note: str | None = None,
) -> None:
    """cards: (id_suffix, front, back, learn_slug) — id becomes pool:{prefix}:{suffix}"""
    prefix = filename.replace(".ts", "").replace("_", "-")
    lines = [
        "import type { TopicDeck } from '@/data/learning-map/decks/types'",
        "",
        f"export const {export_name}: TopicDeck = {{",
        f"  branchTitle: {branch_title!r},",
    ]
    if source_note:
        lines.append(f"  sourceNote: {source_note!r},")
    lines.append("  cards: [")
    seen_ids: set[str] = set()
    for suffix, front, back, learn in cards:
        cid = f"pool:{prefix}:{suffix}"
        if cid in seen_ids:
            raise SystemExit(f"duplicate id {cid}")
        seen_ids.add(cid)
        front_js = front.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
        back_js = back.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")
        lines.append("    {")
        lines.append(f"      id: {cid!r},")
        lines.append(f"      front: `{front_js}`,")
        lines.append(f"      back: `{back_js}`,")
        lines.append(f"      learnSlug: {learn!r},")
        lines.append("    },")
    lines.append("  ],")
    lines.append("}")
    lines.append("")
    (OUT / filename).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {filename}: {len(cards)} cards")


