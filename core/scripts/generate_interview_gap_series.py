def patch_capstones() -> None:
    for path in LEARN.rglob("*.md"):
        text = path.read_text(encoding="utf-8")
        slug = ""
        for line in text.splitlines():
            if line.startswith("slug:"):
                slug = line.split(":", 1)[1].strip()
                break
        block = CAPSTONE_BLOCKS.get(slug)
        if not block or "## Раздел: Ответ вслух" in text:
            continue
        needle = "## Раздел:"
        index = text.find(needle)
        if index < 0:
            print(f"skip {slug}: no section")
            continue
        text = text[:index] + block + text[index:]
        path.write_text(text, encoding="utf-8")
        print(f"patched {path.relative_to(LEARN)}")


def write_articles(articles: list[dict]) -> None:
    for article in articles:
        folder = LEARN / article["folder"]
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / f"{article['slug']}.md"
        path.write_text(_md(article), encoding="utf-8")
        print(f"wrote {path.relative_to(LEARN)}")
    folders = sorted({article["folder"] for article in articles})
    for folder_name in folders:
        rows = [item for item in articles if item["folder"] == folder_name]
        lines = [
            f"# Серия {folder_name}",
            "",
            "Короткие выпуски под дыры собеседования. В каждом есть ответ вслух и плохой ответ.",
            "",
            "| Ep | slug | Тема |",
            "|----|------|------|",
        ]
        for item in rows:
            lines.append(f"| {item['episode']} | `{item['slug']}` | {item['title']} |")
        lines.append("")
        (LEARN / folder_name / "SERIES.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    articles = build_articles()
    write_articles(articles)
    patch_capstones()
    print(f"articles={len(articles)}")


