def _md(article: dict) -> str:
    profiles = "[" + ", ".join(article["profiles"]) + "]"
    tags = "[" + ", ".join(article["tags"]) + "]"
    prereq = "[" + ", ".join(article["prereq"]) + "]"
    sections = "\n".join(
        f"## Раздел: {heading}\n\n{body.strip()}\n" for heading, body in article["sections"]
    )
    quiz = "\n".join(
        f"### {question}\n\n**Ответ:** {answer}\n\n**Пояснение:** {explain}\n"
        for question, answer, explain in article["quiz"]
    )
    anki = "\n".join(
        f"### Front: {front}\n\nBack: {back}\n" for front, back in article["anki"]
    )
    summary = "\n".join(f"- {line}" for line in article["summary"])
    links = "\n".join(f"- [{label}]({href})" for label, href in article["links"])
    cheatsheet = "<ul>" + "".join(f"<li>{line}</li>" for line in article["summary"]) + "</ul>"
    return f"""---
slug: {article["slug"]}
title: {article["title"]}
shortTitle: {article["short"]}
episode: {article["episode"]}
rubric: {article["rubric"]}
order: {article["order"]}
publishedAt: {article["published"]}
profiles: {profiles}
level: {article["level"]}
tags: {tags}
onKnowledgeMap: true
durationMin: {article["minutes"]}
excerpt: {article["excerpt"]}
prerequisites: {prereq}
seoTitle: {article["title"]}
seoDescription: {article["excerpt"]}
seoKeywords: {tags}
canonicalUrl: https://9to18.ru/game/learn/{article["slug"]}
---

## Введение

{article["intro"].strip()}

{sections}
## Лаба

{article["lab"].strip()}

## Схема: {article["diagram"]}

```mermaid
{article["mermaid"].strip()}
```

## Тест

{quiz}
## Шпаргалка

{cheatsheet}

## Anki

{anki}
## Итоги

{summary}

## Ссылки

{links}
"""


def _article(
    *,
    folder: str,
    slug: str,
    title: str,
    short: str,
    episode: str,
    rubric: str,
    order: int,
    level: str,
    profiles: list[str],
    tags: list[str],
    excerpt: str,
    prereq: list[str],
    intro: str,
    sections: list[tuple[str, str]],
    lab: str,
    diagram: str,
    mermaid: str,
    quiz: list[tuple[str, str, str]],
    anki: list[tuple[str, str]],
    summary: list[str],
    links: list[tuple[str, str]],
    minutes: int = 25,
) -> dict:
    spoken = sections
    return {
        "folder": folder,
        "slug": slug,
        "title": title,
        "short": short,
        "episode": episode,
        "rubric": rubric,
        "order": order,
        "level": level,
        "profiles": profiles,
        "tags": tags + ["собеседование"],
        "excerpt": excerpt,
        "prereq": prereq,
        "intro": intro,
        "sections": spoken,
        "lab": lab,
        "diagram": diagram,
        "mermaid": mermaid,
        "quiz": quiz,
        "anki": anki,
        "summary": summary,
        "links": links,
        "minutes": minutes,
        "published": f"2026-10-23T{10 + (order % 8):02d}:00:00+03:00",
    }


def _tail(spoken: str, bad: str, terms: str) -> list[tuple[str, str]]:
    return [
        ("Ответ вслух", spoken),
        ("Плохой ответ", bad),
        ("Термины", terms),
    ]


def _five(items: list[tuple[str, str, str]]) -> list[tuple[str, str, str]]:
    if len(items) != 5:
        raise SystemExit(f"quiz must be 5, got {len(items)}")
    return items


def _six(items: list[tuple[str, str]]) -> list[tuple[str, str]]:
    if len(items) != 6:
        raise SystemExit(f"anki must be 6, got {len(items)}")
    return items


