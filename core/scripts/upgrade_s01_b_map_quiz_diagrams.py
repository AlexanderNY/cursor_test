def apply_to_seed(path: Path) -> tuple[int, int]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise SystemExit(f"{path}: not a list")
    quiz_n = 0
    diag_n = 0
    for item in data:
        if not isinstance(item, dict):
            continue
        slug = item.get("slug")
        patch = PATCHES.get(str(slug or ""))
        if not patch:
            continue
        structured = item.get("structured")
        if not isinstance(structured, dict):
            structured = {"version": 1}
            item["structured"] = structured
        structured["quiz"] = patch["quiz"]
        quiz_n += 1
        if "diagram" in patch:
            structured["diagrams"] = [patch["diagram"]]
            # Keep legacy flat diagram field in sync when present.
            item["diagram"] = patch["diagram"]["mermaid"]
            diag_n += 1
        # Drop meta-only quiz residue from theory if it was the only check.
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    return quiz_n, diag_n


def main() -> None:
    expected = set(PATCHES)
    for path in SEED_PATHS:
        quiz_n, diag_n = apply_to_seed(path)
        data = json.loads(path.read_text(encoding="utf-8"))
        found = {i.get("slug") for i in data if isinstance(i, dict)}
        missing = sorted(expected - found)
        weak = [
            i.get("slug")
            for i in data
            if isinstance(i, dict)
            and i.get("slug") in expected
            and len((i.get("structured") or {}).get("quiz") or []) < 5
        ]
        print(f"{path.relative_to(ROOT)}: patched_quiz={quiz_n} diagrams_set={diag_n}")
        if missing:
            print("  MISSING slugs:", missing)
        if weak:
            print("  STILL WEAK:", weak)


if __name__ == "__main__":
    main()
